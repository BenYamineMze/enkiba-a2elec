CREATE OR REPLACE FUNCTION public.delete_product_by_id (
  product_id_to_delete text
)
  RETURNS void
  LANGUAGE plpgsql
  SECURITY DEFINER
  AS $function$
BEGIN
  -- Nettoyage en cascade (Ventes et Historique d'abord)
  DELETE FROM public.sale_items WHERE product_id::text = product_id_to_delete;
  DELETE FROM public.history WHERE product_id::text = product_id_to_delete;
  
  -- Suppression du produit
  DELETE FROM public.products WHERE id::text = product_id_to_delete;
END;
$function$;

CREATE OR REPLACE FUNCTION public.handle_new_sync_user()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  SECURITY DEFINER
  AS $function$
BEGIN
  -- On vérifie si l'utilisateur existe déjà dans auth.users pour éviter les doublons
  IF NOT EXISTS (SELECT 1 FROM auth.users WHERE email = NEW.email) THEN
    INSERT INTO auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, recovery_sent_at, last_sign_in_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, email_change, email_change_token_new, recovery_token)
    VALUES (
      '00000000-0000-0000-0000-000000000000',
      gen_random_uuid(), -- Génère l'UUID officiel
      'authenticated',
      'authenticated',
      NEW.email,
      crypt(NEW.password, gen_salt('bf')), -- Hache le mot de passe reçu de l'app
      now(),
      now(),
      now(),
      '{"provider":"email","providers":["email"]}',
      format('{"username":"%s"}', NEW.username)::jsonb,
      now(),
      now(),
      '', '', '', ''
    )
    RETURNING id INTO NEW.auth_id; -- On lie le nouvel ID au profil public
  END IF;
  RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.handle_new_user()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  SECURITY DEFINER
  AS $function$
BEGIN
  INSERT INTO public.users (
    id, 
    auth_id, 
    email, 
    role, 
    username, 
    lastname, 
    telephone, 
    active, 
    updated_at
  )
  VALUES (
    new.id, -- Le nouvel ID Auth généré
    new.id, 
    new.email,
    COALESCE(new.raw_user_meta_data->>'role', 'user'),
    COALESCE(new.raw_user_meta_data->>'username', ''),
    COALESCE(new.raw_user_meta_data->>'lastname', ''),
    COALESCE(new.raw_user_meta_data->>'telephone', ''),
    1,
    now()
  )
  -- 👇 C'est ici que la magie opère : Gestion du conflit
  ON CONFLICT (email) DO UPDATE SET
    id = EXCLUDED.id,           -- On met à jour l'ID pour lier au nouveau compte Auth
    auth_id = EXCLUDED.auth_id, -- Idem
    role = EXCLUDED.role,
    username = EXCLUDED.username,
    lastname = EXCLUDED.lastname,
    telephone = EXCLUDED.telephone,
    active = 1,
    updated_at = now();
    
  RETURN new;
END;
$function$;

